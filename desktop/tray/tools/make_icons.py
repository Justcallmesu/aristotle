#!/usr/bin/env python3
"""Regenerates desktop/tray/assets/*.svg and assets/png/*.png (needs rsvg-convert). Run from the repo root.

Glyph paths: docs/design/icon/aristotle-b2-monochrome.svg (T20). Badge shapes: docs/desktop/design.md state-light shapes.
Colours are single per state: each is >= 3:1 against both Breeze panels (#EFF0F1 light, #31363B dark).
"""
import pathlib, subprocess, re

ROOT = pathlib.Path("desktop/tray/assets")
SRC = pathlib.Path("docs/design/icon/aristotle-b2-monochrome.svg").read_text()
PATHS = re.findall(r"<path [^>]*/>", SRC)  # head, neck stroke, hand, body (with the fold hole)
HEAD, NECK, HAND, BODY = PATHS
COLOURS = {"green": "#1E9C77", "amber": "#B87700", "red": "#E5483B"}
SIZES = (16, 22, 24, 32)


def tint(p, colour, extra=""):
    p = p.replace("#000000", colour)
    return p.replace("/>", f" {extra}/>") if extra else p


def badge(state, colour, big):
    # circle / triangle / square, top right where the glyph has no ink; the 16 px one is larger
    if big:
        shapes = {
            "green": '<circle cx="87" cy="17" r="13.5"/>',
            "amber": '<path d="M87 4 100.5 30H73.5Z"/>',
            "red": '<rect x="73.5" y="4" width="27" height="27" rx="2"/>',
        }
    else:
        shapes = {
            "green": '<circle cx="82" cy="22.5" r="9"/>',
            "amber": '<path d="M82 13 91.5 31.5H72.5Z"/>',
            "red": '<rect x="73.5" y="14" width="17" height="17" rx="2"/>',
        }
    return f'<g fill="{colour}">{shapes[state]}</g>'


def svg(state, heavy):
    c = COLOURS[state]
    if heavy:
        # 16 px: head and hand only, strokes thickened so they survive 16 px
        glyph = (tint(HEAD, c, f'stroke="{c}" stroke-width="5" stroke-linejoin="round"')
                 + tint(NECK, c).replace('stroke-width="4.8"', 'stroke-width="8"')
                 + tint(HAND, c, f'stroke="{c}" stroke-width="5" stroke-linejoin="round"'))
        view = "14 2 88 88"
    else:
        glyph = tint(HEAD, c) + tint(NECK, c) + tint(HAND, c) + tint(BODY, c)
        view = "16 10 78 78"
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{view}" width="256" height="256">\n'
            f'<!-- Aristotle tray, {state}{", heavy 16 px (head and hand only)" if heavy else ""}. Generated by tools/make_icons.py -->\n'
            f'{glyph}\n{badge(state, c, heavy)}\n</svg>\n')


def main():
    ROOT.joinpath("png").mkdir(parents=True, exist_ok=True)
    for state in COLOURS:
        for heavy in (False, True):
            name = f"tray-{state}" + ("-16" if heavy else "")
            (ROOT / f"{name}.svg").write_text(svg(state, heavy))
        for px in SIZES:
            src = ROOT / (f"tray-{state}-16.svg" if px == 16 else f"tray-{state}.svg")
            out = ROOT / "png" / f"tray-{state}-{px}.png"
            subprocess.run(["rsvg-convert", "-w", str(px), "-h", str(px), "-o", str(out), str(src)], check=True)


main()
