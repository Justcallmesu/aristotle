package io.github.justcallmesu.aristotle.data

import java.io.File
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

class LicencesTest {
    private val sample = """
        {"schema": 1,
         "licences": [{"id": "apache-2.0", "name": "Apache License 2.0", "text": "licences/apache-2.0.txt"}],
         "components": [
           {"name": "b.lib:zeta", "version": "2.0", "licence": "apache-2.0", "text": "licences/apache-2.0.txt", "copyright": "Copyright B"},
           {"name": "a.lib:Alpha", "version": "1.0", "licence": "apache-2.0", "text": "licences/apache-2.0.txt", "notice": "licences/notice-1.txt", "future": true},
           {"name": "", "version": "1", "licence": "apache-2.0", "text": "licences/apache-2.0.txt"},
           {"name": "c.lib:gamma", "version": "3", "licence": "unlisted", "text": "licences/x.txt"}
         ]}
    """.trimIndent()

    @Test
    fun componentsAreSortedByNameIgnoringCaseAndNamelessOnesAreDropped() {
        val catalog = Licences.parse(sample)!!
        assertEquals(listOf("a.lib:Alpha", "b.lib:zeta", "c.lib:gamma"), catalog.components.map { it.name })
        assertEquals(listOf("apache-2.0"), catalog.kinds.map { it.id })
    }

    @Test
    fun aBrokenOrForeignFileIsNullNotACrash() {
        assertNull(Licences.parse("not json"))
        assertNull(Licences.parse("{}"))
        assertNull(Licences.parse("""{"schema": 2, "licences": [], "components": []}"""))
    }

    @Test
    fun detailCarriesTheLicenceNameTextAndNotice() {
        val catalog = Licences.parse(sample)!!
        val files = mapOf("licences/apache-2.0.txt" to "FULL TEXT\n\n", "licences/notice-1.txt" to "  NOTICE BODY\n")
        val alpha = Licences.detail(catalog, catalog.components[0], files::get)
        assertEquals("Apache License 2.0", alpha.licenceName)
        assertEquals("FULL TEXT", alpha.text)
        assertEquals("NOTICE BODY", alpha.notice)
        assertNull(Licences.detail(catalog, catalog.components[1], files::get).notice)
    }

    @Test
    fun aMissingTextOrUnknownLicenceIsShownAsMissingNotThrown() {
        val catalog = Licences.parse(sample)!!
        val gamma = Licences.detail(catalog, catalog.components[2], { null })
        assertNull(gamma.text)
        assertNull(gamma.licenceName)
        assertEquals("3 · unlisted", Licences.subline(catalog, catalog.components[2]))
        assertEquals("1.0 · Apache License 2.0", Licences.subline(catalog, catalog.components[0]))
    }

    // Unit tests run in android/app. The committed assets are generated by scripts/licences.sh; this guards their shape.
    private val assets = File("src/main/assets")

    @Test
    fun theCommittedAssetIsAWellFormedCatalogueWithEveryTextPresent() {
        val catalog = Licences.parse(File(assets, Licences.CATALOG_ASSET).readText())
        assertNotNull(catalog)
        catalog!!
        assertTrue("components: ${catalog.components.size}", catalog.components.size > 50)
        catalog.kinds.forEach { assertTrue("kind text ${it.text}", File(assets, it.text).readText().isNotBlank()) }
        catalog.components.forEach { c ->
            assertTrue("licence of ${c.name}", catalog.kindName(c.licence) != null)
            assertTrue("text of ${c.name}", File(assets, c.text).isFile)
            assertTrue("copyright of ${c.name}", c.copyright.isNotBlank())
            c.notice?.let { assertTrue("notice of ${c.name}", File(assets, it).isFile) }
        }
    }

    @Test
    fun theAssetListsTheDependenciesTheDecisionNames() {
        val names = Licences.parse(File(assets, Licences.CATALOG_ASSET).readText())!!.components.map { it.name }
        listOf(
            "com.github.termux.termux-app:terminal-emulator",
            "androidx.compose.ui:ui-android",
            "com.squareup.okhttp3:okhttp-android",
            "com.mikepenz:multiplatform-markdown-renderer-m3-android",
            "com.google.android.gms:play-services-code-scanner",
            "Atkinson Hyperlegible Next (font)",
        ).forEach { assertTrue("$it listed", it in names) }
    }
}
