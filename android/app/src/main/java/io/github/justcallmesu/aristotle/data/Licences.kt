package io.github.justcallmesu.aristotle.data

import kotlinx.serialization.Serializable
import kotlinx.serialization.json.Json

/** One licence of the catalogue: [text] is the asset path of its full text. */
@Serializable
data class LicenceKind(val id: String, val name: String, val text: String)

/** One third-party component shipped in the app (a library or a font). [notice] is the asset path of its NOTICE, if it has one. */
@Serializable
data class LicenceComponent(
    val name: String,
    val version: String,
    val licence: String,
    val text: String,
    val copyright: String = "",
    val notice: String? = null,
)

/** What the licence page shows for one component, before it is turned into screen text. */
data class LicenceDetail(
    val component: LicenceComponent,
    val licenceName: String?,
    val notice: String?,
    /** The licence text; null when its asset is missing. */
    val text: String?,
)

@Serializable
private class LicenceFile(
    val schema: Int = 0,
    val licences: List<LicenceKind> = emptyList(),
    val components: List<LicenceComponent> = emptyList(),
)

class LicenceCatalog(val kinds: List<LicenceKind>, val components: List<LicenceComponent>) {
    fun kindName(id: String): String? = kinds.firstOrNull { it.id == id }?.name
}

/**
 * The open-source licence notices (D45). `assets/licences.json` is generated by `scripts/licences.sh` from the release
 * classpath; this only reads it, so a bad file shows as an empty list and never as a crash.
 */
object Licences {
    const val CATALOG_ASSET = "licences.json"
    private const val SCHEMA = 1
    private val json = Json { ignoreUnknownKeys = true }

    /** The catalogue with components sorted by name; null when [text] is not a catalogue of this schema. */
    fun parse(text: String): LicenceCatalog? {
        val file = runCatching { json.decodeFromString<LicenceFile>(text) }.getOrNull() ?: return null
        if (file.schema != SCHEMA) return null
        val components = file.components
            .filter { it.name.isNotBlank() && it.text.isNotBlank() }
            .sortedWith(compareBy({ it.name.lowercase() }, { it.version }))
        return LicenceCatalog(file.licences, components)
    }

    /** Reads [component]'s licence and NOTICE texts through [load] (an asset reader, null when missing). */
    fun detail(catalog: LicenceCatalog, component: LicenceComponent, load: (String) -> String?): LicenceDetail =
        LicenceDetail(
            component = component,
            licenceName = catalog.kindName(component.licence),
            notice = component.notice?.let(load)?.trim()?.takeIf { it.isNotEmpty() },
            text = load(component.text)?.trimEnd()?.takeIf { it.isNotEmpty() },
        )

    /** The list row's second line: the version, then the licence's name. */
    fun subline(catalog: LicenceCatalog, component: LicenceComponent): String =
        listOfNotNull(component.version.takeIf { it.isNotBlank() }, catalog.kindName(component.licence) ?: component.licence)
            .joinToString(" · ")
}
