/** Component and licence texts read from the APK's assets (generated by scripts/licences.sh). */
private class LoadedLicences(val catalog: LicenceCatalog?, val read: (String) -> String?)

/**
 * About › Open-source licences (D45): every third-party component by name; a tap opens its licence as plain,
 * scrollable text. The open component is kept across rotation by its key (name and version).
 */
@Composable
fun LicencesScreen(onBack: () -> Unit) {
    val context = LocalContext.current
    val loaded by produceState<LoadedLicences?>(null) {
        value = withContext(Dispatchers.IO) {
            val read: (String) -> String? = { path ->
                runCatching { context.assets.open(path).bufferedReader().use { it.readText() } }.getOrNull()
            }
            LoadedLicences(read(Licences.CATALOG_ASSET)?.let(Licences::parse), read)
        }
    }
    var openKey by rememberSaveable { mutableStateOf("") }
    val source = loaded
    val catalog = source?.catalog
    val open = catalog?.components?.firstOrNull { componentKey(it) == openKey }
    BackHandler(enabled = open != null) { openKey = "" }
    Surface(modifier = Modifier.fillMaxSize(), color = MaterialTheme.colorScheme.surface) {
        Column(modifier = Modifier.fillMaxSize().windowInsetsPadding(WindowInsets.safeDrawing)) {
            SubPageTopBar(open?.name ?: stringResource(R.string.settings_licences), onBack = { if (open != null) openKey = "" else onBack() })
            when {
                source == null -> Unit
                catalog == null || catalog.components.isEmpty() -> Message(stringResource(R.string.licences_empty))
                open != null -> LicenceText(Licences.detail(catalog, open, source.read))
                else -> LicenceList(catalog, onOpen = { openKey = componentKey(it) })
            }
        }
    }
}

private fun componentKey(c: LicenceComponent): String = c.name + "@" + c.version

@Composable
private fun Message(text: String) {
    Text(
        text = text,
        style = MaterialTheme.typography.bodyMedium,
        color = MaterialTheme.colorScheme.onSurfaceVariant,
        modifier = Modifier.padding(horizontal = Spacing.xxl, vertical = Spacing.xs),
    )
}

@Composable
private fun LicenceList(catalog: LicenceCatalog, onOpen: (LicenceComponent) -> Unit) {
    LazyColumn(modifier = Modifier.fillMaxSize()) {
        items(catalog.components, key = ::componentKey) { component ->
            Column(
                modifier = Modifier
                    .fillMaxWidth()
                    .heightIn(min = Sizes.listRowHeight)
                    .clickable { onOpen(component) }
                    .padding(horizontal = Spacing.xxl, vertical = Spacing.s),
                verticalArrangement = Arrangement.Center,
            ) {
                Text(component.name, style = MaterialTheme.typography.bodyLarge, maxLines = 2, overflow = TextOverflow.Ellipsis)
                Text(
                    Licences.subline(catalog, component),
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                )
            }
        }
    }
}

@Composable
private fun LicenceText(detail: LicenceDetail) {
    val c = detail.component
    Column(
        modifier = Modifier
            .fillMaxSize()
            .verticalScroll(rememberScrollState())
            .padding(start = Spacing.xxl, end = Spacing.xxl, top = Spacing.xs, bottom = Spacing.xxl),
    ) {
        Text(c.name + " " + c.version, style = MaterialTheme.typography.titleMedium)
        if (c.copyright.isNotBlank()) Text(c.copyright, style = MaterialTheme.typography.bodyMedium, modifier = Modifier.padding(top = Spacing.xs))
        Text(
            stringResource(R.string.licences_licence_label, detail.licenceName ?: c.licence),
            style = MaterialTheme.typography.bodyMedium,
            color = MaterialTheme.colorScheme.onSurfaceVariant,
            modifier = Modifier.padding(top = Spacing.xs, bottom = Spacing.l),
        )
        detail.notice?.let { notice ->
            Text(stringResource(R.string.licences_notice_heading), style = MaterialTheme.typography.titleSmall)
            Text(notice, style = MaterialTheme.typography.bodySmall, modifier = Modifier.padding(top = Spacing.xs, bottom = Spacing.l))
        }
        Text(
            detail.text ?: stringResource(R.string.licences_text_missing),
            style = MaterialTheme.typography.bodySmall,
            color = if (detail.text == null) MaterialTheme.colorScheme.error else MaterialTheme.colorScheme.onSurface,
        )
    }
}
